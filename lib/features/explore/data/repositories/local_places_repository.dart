  Future<List<Place>> getPlaces() async {
    return _curatedPlaces;
  }

  Future<List<Place>> getCuratedPlaces() async {
    return _curatedPlaces;
  }

  @override
  Future<Place?> getPlaceById(String id) async {
    try {
      if (id == 'shivagiri') {
        return _curatedPlaces.firstWhere((p) => p.id == 'shivgiri');
      }
      if (id == 'bara_kamaan') {
        return _curatedPlaces.firstWhere((p) => p.id == 'bara_kaman');
      }
      if (id == 'upli_buruz') {
        return _curatedPlaces.firstWhere((p) => p.id == 'upli_burj');
      }
      return _curatedPlaces.firstWhere((p) => p.id == id);
    } catch (_) {
      return null;
    }
  }

  @override
  Future<List<Place>> getPlacesByCategory(String category) async {
    final cat = category.toLowerCase();
    if (cat == 'all') {
      return _curatedPlaces;
    }
    if (cat == 'temples & shrines') {
      return _curatedPlaces.where((p) {
        final pCat = p.category.toLowerCase();
        return pCat == 'temples & shrines' ||
            pCat.contains('temple') ||
            pCat.contains('shrine') ||
            pCat.contains('math') ||
            pCat.contains('vihar') ||
            pCat.contains('religious');
      }).toList();
    }
    return _curatedPlaces
        .where((p) => p.category.toLowerCase() == cat)
        .toList();
  }

  @override
  Future<List<Place>> searchPlaces(String query) async {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return _curatedPlaces;
    return _curatedPlaces.where((p) {
      return p.name.toLowerCase().contains(q) ||
          p.shortDescription.toLowerCase().contains(q) ||
          p.historicalOverview.toLowerCase().contains(q) ||
          p.category.toLowerCase().contains(q) ||
          p.locationName.toLowerCase().contains(q) ||
          (p.village?.toLowerCase().contains(q) ?? false) ||
          (p.taluka?.toLowerCase().contains(q) ?? false) ||
          (p.district?.toLowerCase().contains(q) ?? false);
    }).toList();
  }

