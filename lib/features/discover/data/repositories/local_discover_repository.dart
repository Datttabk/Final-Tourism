  /// Fetch all hotels, optionally filtered by search term.
  /// Searches across hotel name and address.
  Future<List<Hotel>> getHotels({String? searchQuery}) async {
    if (searchQuery == null || searchQuery.trim().isEmpty) {
      return List.unmodifiable(_hotels);
    }

    final query = searchQuery.trim().toLowerCase();
    return _hotels.where((hotel) {
      final nameMatches = hotel.name.toLowerCase().contains(query);
      final addressMatches = hotel.address.toLowerCase().contains(query);
      final talukaMatches = hotel.taluka.toLowerCase().contains(query);
      final typeMatches = hotel.type.toLowerCase().contains(query);
      final destMatches = hotel.nearestTouristDestination
          .toLowerCase()
          .contains(query);
      return nameMatches ||
          addressMatches ||
          talukaMatches ||
          typeMatches ||
          destMatches;
    }).toList();
  }

  /// Fetch all tourist guides, optionally filtered by search term.
  /// Searches across guide name and languages spoken.
  Future<List<TouristGuide>> getTouristGuides({String? searchQuery}) async {
    if (searchQuery == null || searchQuery.trim().isEmpty) {
      return List.unmodifiable(_guides);
    }

    final query = searchQuery.trim().toLowerCase();
    return _guides.where((guide) {
      final nameMatches = guide.name.toLowerCase().contains(query);
      final langMatches = guide.languagesSpoken.any(
        (lang) => lang.toLowerCase().contains(query),
